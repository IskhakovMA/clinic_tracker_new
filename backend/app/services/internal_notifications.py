"""Computed internal notification inbox with per-user read state.

This is intentionally separate from the outbound/mock notification queue. The
active conditions are derived from scoped domain data on every request; only the
employee's read state is persisted.
"""
from __future__ import annotations

import hashlib
import sqlite3
from dataclasses import dataclass
from datetime import date, timedelta
from typing import Any

from .. import audit, config, policy
from ..analytics.filters import app_timezone, today_local
from ..db import in_chunks, now_iso, temp_id_table
from . import data_quality, patient_attention
from ..models import TERMINAL_STAGES

TYPES = ("overdue", "today", "upcoming", "checklist", "data_quality", "attention", "consilium_revision")
DRAWER_FILTERS = ("all", "unread", "today", "overdue", "attention")
QUALITY_SEVERITIES = {"critical", "warning"}
UPCOMING_DAYS = max(1, min(config.INTERNAL_NOTIFICATION_UPCOMING_DAYS, 30))
TERMINAL_STAGE_SET = set(TERMINAL_STAGES)


@dataclass(frozen=True)
class Condition:
    stable_key: str
    patient_id: str
    notification_type: str
    source_type: str
    source_id: str
    title: str
    description: str
    event_at: str
    priority: str
    patient_name: str
    stage: str


def _state_id(user_id: str, stable_key: str) -> str:
    raw = f"{user_id}\x1f{stable_key}"
    return "in_" + hashlib.sha256(raw.encode("utf-8")).hexdigest()[:32]


def _safe_date(value: str | None) -> date | None:
    if not value:
        return None
    try:
        return date.fromisoformat(str(value)[:10])
    except ValueError:
        return None


def _event_time(row: sqlite3.Row) -> str:
    day = row["date"] or ""
    time = (row["time"] or "").strip()
    return f"{day}T{time}:00" if time else day


def _event_title(kind: str, days: int) -> str:
    if kind == "overdue":
        return f"Просрочено на {days} дн."
    if kind == "today":
        return "На сегодня"
    return f"Скоро срок: {days} дн."


def _event_description(kind: str) -> str:
    if kind == "overdue":
        return "Контрольное действие не выполнено."
    if kind == "today":
        return "Сегодня запланировано контрольное действие."
    return "Запланированное действие скоро наступит."


def _scoped_patient_rows(conn: sqlite3.Connection, user: policy.CurrentUser) -> list[sqlite3.Row]:
    cond, params = policy.patient_scope_filter(user)
    return conn.execute(
        f"""SELECT patients.id, patients.name, patients.stage
            FROM patients
            WHERE {cond}
            ORDER BY patients.name ASC, patients.id ASC""",  # nosec B608 - condition is generated by patient scope policy.
        params,
    ).fetchall()


def _event_conditions(conn: sqlite3.Connection, user: policy.CurrentUser, today: date) -> list[Condition]:
    cond, params = policy.patient_scope_filter(user)
    rows = conn.execute(
        f"""SELECT patients.id AS patient_id, patients.name AS patient_name, patients.stage,
                   e.id AS event_id, e.date, e.time
            FROM events e
            JOIN history_entries h ON h.id = e.history_entry_id
            JOIN patients ON patients.id = h.patient_id
            WHERE {cond}
              AND patients.stage NOT IN ({','.join('?' for _ in TERMINAL_STAGE_SET)})
              AND COALESCE(e.no_plan, 0) = 0
              AND e.date IS NOT NULL AND e.date != ''
              AND (e.actual_date IS NULL OR e.actual_date = '')
            ORDER BY e.date ASC, e.time ASC, patients.name ASC, e.id ASC""",  # nosec B608 - condition is generated by patient scope policy.
        [*params, *sorted(TERMINAL_STAGE_SET)],
    ).fetchall()
    result: list[Condition] = []
    for row in rows:
        day = _safe_date(row["date"])
        if day is None:
            continue
        delta = (day - today).days
        if delta < 0:
            kind = "overdue"
            priority = "high"
            title_days = abs(delta)
        elif delta == 0:
            kind = "today"
            priority = "normal"
            title_days = 0
        elif 1 <= delta <= UPCOMING_DAYS:
            kind = "upcoming"
            priority = "normal"
            title_days = delta
        else:
            continue
        source_id = row["event_id"]
        stable_key = f"{kind}:event:{source_id}:{row['date']}"
        result.append(Condition(
            stable_key=stable_key,
            patient_id=row["patient_id"],
            notification_type=kind,
            source_type="event",
            source_id=source_id,
            title=_event_title(kind, title_days),
            description=_event_description(kind),
            event_at=_event_time(row),
            priority=priority,
            patient_name=row["patient_name"] or "Пациент",
            stage=row["stage"] or "",
        ))
    return result


def _quality_conditions(conn: sqlite3.Connection, user: policy.CurrentUser, today: date) -> list[Condition]:
    result = data_quality.evaluate(conn, user, today=today)
    computed_at = result["summary"]["computed_at"]
    patient_map = {p["patient_id"]: p for p in result["patients"]}
    conditions: list[Condition] = []
    for issue in result["issues"]:
        patient_id = issue["patient_id"]
        patient = patient_map.get(patient_id)
        if not patient:
            continue
        code = issue["code"]
        if code == "incomplete_required_checklist":
            missing = int((issue.get("details") or {}).get("missing_count") or 0)
            if missing <= 0:
                continue
            conditions.append(Condition(
                stable_key=f"checklist:data_quality:{patient_id}:{code}",
                patient_id=patient_id,
                notification_type="checklist",
                source_type="checklist",
                source_id=code,
                title="Незавершённый чек-лист",
                description="Обязательные пункты чек-листа не отмечены выполненными.",
                event_at=computed_at,
                priority="normal",
                patient_name=patient["patient_name"],
                stage=patient.get("stage") or patient.get("stage_code") or "",
            ))
            continue
        if issue["severity"] not in QUALITY_SEVERITIES:
            continue
        conditions.append(Condition(
            stable_key=f"data_quality:{patient_id}:{code}:{issue.get('field') or ''}",
            patient_id=patient_id,
            notification_type="data_quality",
            source_type="data_quality",
            source_id=code,
            title=issue["title"],
            description="Значимая проблема качества данных требует проверки.",
            event_at=computed_at,
            priority="high" if issue["severity"] == "critical" else "normal",
            patient_name=patient["patient_name"],
            stage=patient.get("stage") or patient.get("stage_code") or "",
        ))
    return conditions


def _attention_conditions(conn: sqlite3.Connection, user: policy.CurrentUser) -> list[Condition]:
    result: list[Condition] = []
    for row in patient_attention.active_conditions(conn, user):
        reason = patient_attention.reason_label(row["reason_code"])
        result.append(Condition(
            stable_key=f"attention:issue:{row['issue_id']}",
            patient_id=row["patient_id"],
            notification_type="attention",
            source_type="attention",
            source_id=row["issue_id"],
            title="Требует внимания",
            description=f"Причина: {reason}",
            event_at=row["event_date"] or row["created_at"],
            priority="high" if row["reason_code"] in {"emergency_hospitalization", "critical_overdue"} else "normal",
            patient_name=row["patient_name"] or "Пациент",
            stage=row["stage"] or "",
        ))
    return result


def _consilium_revision_conditions(
    conn: sqlite3.Connection, user: policy.CurrentUser
) -> list[Condition]:
    rows = conn.execute(
        """SELECT a.id AS appointment_id, a.patient_id, a.updated_at,
                  patients.name AS patient_name, patients.stage
           FROM oncology_consilium_appointments a
           JOIN patients ON patients.id = a.patient_id
           WHERE a.created_by_user_id = ?
             AND a.status = 'recorded'
             AND COALESCE(a.revision_comment, '') != ''
             AND a.revision_submitted_at IS NULL
             AND a.archived_at IS NULL
           ORDER BY a.updated_at ASC, a.id ASC""",
        (user.id,),
    ).fetchall()
    return [Condition(
        stable_key=f"consilium_revision:appointment:{row['appointment_id']}:{row['updated_at']}",
        patient_id=row["patient_id"],
        notification_type="consilium_revision",
        source_type="consilium_revision",
        source_id=row["appointment_id"],
        title="Консилиум возвращён на доработку",
        description="Председатель оставил комментарий. Откройте запись, внесите изменения и отправьте её повторно.",
        event_at=row["updated_at"],
        priority="high",
        patient_name=row["patient_name"] or "Пациент",
        stage=row["stage"] or "",
    ) for row in rows]


def _compute_conditions(conn: sqlite3.Connection, user: policy.CurrentUser) -> list[Condition]:
    today = today_local()
    merged: dict[str, Condition] = {}
    for condition in [
        *_event_conditions(conn, user, today),
        *_quality_conditions(conn, user, today),
        *_attention_conditions(conn, user),
        *_consilium_revision_conditions(conn, user),
    ]:
        merged.setdefault(condition.stable_key, condition)
    return [merged[key] for key in sorted(merged)]


def _sync_state(conn: sqlite3.Connection, user: policy.CurrentUser, conditions: list[Condition]) -> dict[str, sqlite3.Row]:
    now = now_iso()
    active_keys = {c.stable_key for c in conditions}
    with conn:
        for c in conditions:
            sid = _state_id(user.id, c.stable_key)
            conn.execute(
                """INSERT INTO internal_notification_state
                   (id, user_id, stable_key, patient_id, notification_type, source_type, source_id,
                    first_seen_at, last_seen_at, read_at, resolved_at)
                   VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, NULL, NULL)
                   ON CONFLICT(user_id, stable_key) DO UPDATE SET
                       patient_id = excluded.patient_id,
                       notification_type = excluded.notification_type,
                       source_type = excluded.source_type,
                       source_id = excluded.source_id,
                       last_seen_at = excluded.last_seen_at,
                       resolved_at = NULL""",
                (sid, user.id, c.stable_key, c.patient_id, c.notification_type, c.source_type, c.source_id, now, now),
            )
        if active_keys:
            keys = temp_id_table(conn, sorted(active_keys))
            conn.execute(
                f"""UPDATE internal_notification_state
                    SET resolved_at = COALESCE(resolved_at, ?)
                    WHERE user_id = ? AND resolved_at IS NULL AND stable_key NOT IN (SELECT id FROM {keys})""",  # nosec B608 - generated identifier
                [now, user.id],
            )
        else:
            conn.execute(
                """UPDATE internal_notification_state
                   SET resolved_at = COALESCE(resolved_at, ?)
                   WHERE user_id = ? AND resolved_at IS NULL""",
                (now, user.id),
            )
    ids = [_state_id(user.id, c.stable_key) for c in conditions]
    if not ids:
        return {}
    rows = []
    for chunk in in_chunks(conn, ids):
        marks = ",".join("?" for _ in chunk)
        rows.extend(conn.execute(
            f"""SELECT * FROM internal_notification_state
                WHERE user_id = ? AND id IN ({marks})""",  # nosec B608 - ids are generated server-side and bound.
            [user.id, *chunk],
        ).fetchall())
    return {row["stable_key"]: row for row in rows}


def _type_label(kind: str) -> str:
    return {
        "overdue": "Просрочено",
        "today": "Сегодня",
        "upcoming": "Скоро",
        "checklist": "Чек-листы",
        "data_quality": "Качество данных",
        "attention": "Требует внимания",
        "consilium_revision": "Доработка консилиума",
    }.get(kind, kind)


def _to_item(condition: Condition, state: sqlite3.Row) -> dict:
    read_at = state["read_at"]
    return {
        "id": state["id"],
        "type": condition.notification_type,
        "type_label": _type_label(condition.notification_type),
        "title": condition.title,
        "description": condition.description,
        "patient_id": condition.patient_id,
        "patient_name": condition.patient_name,
        "stage": condition.stage,
        "source_type": condition.source_type,
        "source_id": condition.source_id,
        "event_at": condition.event_at,
        "first_seen_at": state["first_seen_at"],
        "last_seen_at": state["last_seen_at"],
        "read": read_at is not None,
        "read_at": read_at,
        "priority": condition.priority,
    }


def _active_items(conn: sqlite3.Connection, user: policy.CurrentUser) -> list[dict]:
    conditions = _compute_conditions(conn, user)
    states = _sync_state(conn, user, conditions)
    items = [_to_item(c, states[c.stable_key]) for c in conditions if c.stable_key in states]
    return sorted(items, key=lambda x: (x["read"], x["event_at"] or "", x["patient_name"], x["id"]))


def summary(conn: sqlite3.Connection, user: policy.CurrentUser) -> dict:
    items = _active_items(conn, user)
    return {
        "computed_at": now_iso(),
        "timezone": config.APP_TIMEZONE,
        "scope": user.scope_strategy,
        "upcoming_days": UPCOMING_DAYS,
        "total_count": len(items),
        "unread_count": sum(1 for i in items if not i["read"]),
        "overdue_count": sum(1 for i in items if i["type"] == "overdue"),
        "today_count": sum(1 for i in items if i["type"] == "today"),
        "upcoming_count": sum(1 for i in items if i["type"] == "upcoming"),
        "checklist_count": sum(1 for i in items if i["type"] == "checklist"),
        "quality_count": sum(1 for i in items if i["type"] == "data_quality"),
        "attention_count": sum(1 for i in items if i["type"] == "attention"),
        "consilium_revision_count": sum(1 for i in items if i["type"] == "consilium_revision"),
    }


def preview_summary(conn: sqlite3.Connection, user: policy.CurrentUser) -> dict:
    """Read-only summary for AI tools.

    Unlike summary()/list_items(), this deliberately does not synchronise
    internal_notification_state and therefore cannot mark anything seen/read.
    """
    conditions = _compute_conditions(conn, user)
    return {
        "computed_at": now_iso(),
        "timezone": config.APP_TIMEZONE,
        "scope": user.scope_strategy,
        "upcoming_days": UPCOMING_DAYS,
        "total_count": len(conditions),
        "unread_count": None,
        "overdue_count": sum(1 for i in conditions if i.notification_type == "overdue"),
        "today_count": sum(1 for i in conditions if i.notification_type == "today"),
        "upcoming_count": sum(1 for i in conditions if i.notification_type == "upcoming"),
        "checklist_count": sum(1 for i in conditions if i.notification_type == "checklist"),
        "quality_count": sum(1 for i in conditions if i.notification_type == "data_quality"),
        "attention_count": sum(1 for i in conditions if i.notification_type == "attention"),
        "consilium_revision_count": sum(1 for i in conditions if i.notification_type == "consilium_revision"),
        "read_state": "not_changed",
    }


def list_items(
    conn: sqlite3.Connection,
    user: policy.CurrentUser,
    *,
    unread_only: bool = False,
    type: str | None = None,
    drawer_filter: str = "all",
    search: str | None = None,
    limit: int = 50,
    offset: int = 0,
) -> dict:
    if type and type not in TYPES:
        raise ValueError("unknown notification type")
    if drawer_filter not in DRAWER_FILTERS:
        raise ValueError("unknown drawer filter")
    items = _active_items(conn, user)
    if unread_only or drawer_filter == "unread":
        items = [i for i in items if not i["read"]]
    if drawer_filter == "today":
        items = [i for i in items if i["type"] == "today"]
    if drawer_filter == "overdue":
        items = [i for i in items if i["type"] == "overdue"]
    if drawer_filter == "attention":
        items = [i for i in items if i["type"] == "attention"]
    if type:
        items = [i for i in items if i["type"] == type]
    if search:
        needle = " ".join(search.lower().split())
        items = [i for i in items if needle in i["patient_name"].lower()]
    total = len(items)
    return {
        "items": items[offset:offset + limit],
        "total": total,
        "limit": limit,
        "offset": offset,
        "summary": summary(conn, user),
    }


def mark_read(conn: sqlite3.Connection, user: policy.CurrentUser, notification_id: str) -> dict | None:
    items = _active_items(conn, user)
    item = next((i for i in items if i["id"] == notification_id), None)
    if item is None:
        return None
    now = now_iso()
    with conn:
        conn.execute(
            """UPDATE internal_notification_state
               SET read_at = COALESCE(read_at, ?)
               WHERE id = ? AND user_id = ? AND resolved_at IS NULL""",
            (now, notification_id, user.id),
        )
    audit.record(
        conn,
        audit.INTERNAL_NOTIFICATION_READ,
        patient_id=item["patient_id"],
        detail=f"type={item['type']} source_type={item['source_type']}",
        **audit.actor_ctx(user),
    )
    return next((i for i in _active_items(conn, user) if i["id"] == notification_id), item)


def mark_all_read(conn: sqlite3.Connection, user: policy.CurrentUser) -> dict:
    items = _active_items(conn, user)
    unread_ids = [i["id"] for i in items if not i["read"]]
    if unread_ids:
        now = now_iso()
        with conn:
            for chunk in in_chunks(conn, unread_ids):
                marks = ",".join("?" for _ in chunk)
                conn.execute(
                    f"""UPDATE internal_notification_state
                        SET read_at = COALESCE(read_at, ?)
                        WHERE user_id = ? AND id IN ({marks})""",  # nosec B608 - ids are generated server-side and bound.
                    [now, user.id, *chunk],
                )
        audit.record(
            conn,
            audit.INTERNAL_NOTIFICATION_READ_ALL,
            detail=f"count={len(unread_ids)}",
            **audit.actor_ctx(user),
        )
    return {"updated": len(unread_ids), "summary": summary(conn, user)}
