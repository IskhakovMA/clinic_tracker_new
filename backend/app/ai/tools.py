def tool_definitions() -> list[dict]:
    return [spec.openai_schema() for spec in TOOLS.values()]


def execute_tool(name: str, raw_args: str | dict | None, conn: sqlite3.Connection, user: policy.CurrentUser) -> dict:
    spec = TOOLS.get(name)
    if spec is None:
        raise ToolExecutionError("Tool не разрешён.")
    return spec.execute(conn, user, raw_args)
