def get_department_attention_summary(conn: sqlite3.Connection, user: policy.CurrentUser, args: EmptyArgs) -> dict:
    if user.scope_strategy == policy.SCOPE_BY_TREATING_DOCTOR:
        raise ToolPermissionError("Сводка отделения недоступна роли врача.")
    return {
        "attention": list_attention_patients(conn, user, ListAttentionArgs(limit=30)),
        "analytics": get_analytics_summary(conn, user, EmptyArgs()),
    }


ToolHandler = Callable[[sqlite3.Connection, policy.CurrentUser, Any], dict]


class ToolSpec:
    def __init__(self, *, name: str, description: str, schema: type[StrictRequestModel], handler: ToolHandler):
        self.name = name
        self.description = description
        self.schema = schema
        self.handler = handler

    def openai_schema(self) -> dict:
        return {
            "type": "function",
            "function": {
                "name": self.name,
                "description": self.description,
                "parameters": self.schema.model_json_schema(),
            },
        }

    def execute(self, conn: sqlite3.Connection, user: policy.CurrentUser, raw_args: str | dict | None) -> dict:
        try:
            payload = json.loads(raw_args or "{}") if isinstance(raw_args, str) else (raw_args or {})
            args = self.schema.model_validate(payload)
        except (json.JSONDecodeError, ValidationError) as exc:
            raise ToolExecutionError("Некорректные аргументы tool.") from exc
        return self.handler(conn, user, args)


