class ToolPermissionError(RuntimeError):
    """The user is authenticated but the tool is not allowed for this role/scope."""


class ToolExecutionError(RuntimeError):
    """Controlled tool execution failure."""


class SearchAccessiblePatientsArgs(StrictRequestModel):
    query: str = Field("", max_length=120)
    limit: int = Field(5, ge=1, le=10)

    @field_validator("query")
    @classmethod
    def _norm_query(cls, value: str) -> str:
        return " ".join((value or "").split())


class PatientIdArgs(StrictRequestModel):
    patientId: str = Field(..., min_length=1, max_length=100)


class TimelineArgs(PatientIdArgs):
    days: int = Field(30, ge=1, le=90)
    limit: int = Field(30, ge=1, le=100)


class ListAttentionArgs(StrictRequestModel):
    reason: str | None = Field(None, max_length=80)
    limit: int = Field(10, ge=1, le=30)

    @field_validator("reason")
    @classmethod
    def _valid_reason(cls, value: str | None) -> str | None:
        if value in (None, ""):
            return None
        if value not in patient_attention.REASON_LABELS:
            raise ValueError("unknown attention reason")
        return value


class ListOverdueArgs(StrictRequestModel):
    bucket: str | None = Field(None, max_length=20)
    limit: int = Field(10, ge=1, le=30)

    @field_validator("bucket")
    @classmethod
    def _valid_bucket(cls, value: str | None) -> str | None:
        if value in (None, ""):
            return None
        if value not in {"1_2", "3_7", "8_14", "15_plus"}:
            raise ValueError("unknown overdue bucket")
        return value


class EmptyArgs(StrictRequestModel):
    pass


def _patient_ref(row: sqlite3.Row | dict, attention: dict | None = None) -> dict:
    getter = row.get if isinstance(row, dict) else row.__getitem__
    attention = attention or {}
    return {
        "patientId": getter("id") if "id" in row.keys() else getter("patient_id"),
        "displayName": getter("name") if "name" in row.keys() else getter("patient_name"),
        "currentStage": getter("stage") or "",
        "currentStageLabel": stage_label(getter("stage") or ""),
        "requiresAttention": bool(attention.get("active")),
        "activeAttentionCount": int(attention.get("activeCount") or 0),
        "untrusted": True,
    }


def _scoped_rows(conn: sqlite3.Connection, user: policy.CurrentUser, *, query: str = "", limit: int = 10) -> list[sqlite3.Row]:
    cond, params = policy.patient_scope_filter(user)
    where = [f"({cond})"]
    args: list[Any] = list(params)
    if query:
        needle = f"%{query}%"
        lower_needle = f"%{query.lower()}%"
        where.append(
            "(patients.name LIKE ? OR patients.nosology LIKE ? "
            "OR LOWER(patients.name) LIKE ? OR LOWER(patients.nosology) LIKE ?)"
        )
        args.extend([needle, needle, lower_needle, lower_needle])
    args.append(limit)
    return conn.execute(
        f"""SELECT patients.id, patients.name, patients.stage
            FROM patients
            WHERE {' AND '.join(where)}
            ORDER BY patients.name ASC, patients.id ASC
            LIMIT ?""",  # nosec B608 - scope condition is generated by policy; other args are bound.
        args,
    ).fetchall()


def _require_patient(conn: sqlite3.Connection, user: policy.CurrentUser, patient_id: str) -> dict:
    if not policy.can_read_patient(conn, user, patient_id):
        raise ToolPermissionError("Пациент недоступен текущей роли.")
    patient = store.patient_to_dict(conn, patient_id)
    if patient is None:
        raise ToolPermissionError("Пациент недоступен текущей роли.")
    return patient


def search_accessible_patients(conn: sqlite3.Connection, user: policy.CurrentUser, args: SearchAccessiblePatientsArgs) -> dict:
    rows = _scoped_rows(conn, user, query=args.query, limit=args.limit)
    summary = patient_attention.bulk_summary(conn, [row["id"] for row in rows])
    return {"patients": [_patient_ref(row, summary.get(row["id"])) for row in rows]}


def get_patient_summary(conn: sqlite3.Connection, user: policy.CurrentUser, args: PatientIdArgs) -> dict:
    patient = _require_patient(conn, user, args.patientId)
    attention = patient_attention.list_for_patient(conn, user, args.patientId, limit=20)
    quality = data_quality.evaluate(conn, user, today=today_local())
    issues = [i for i in quality["issues"] if i["patient_id"] == args.patientId]
    latest = patient["history"][-1] if patient["history"] else {}
    checklist = latest.get("checklist") or {}
    completed = sum(1 for value in checklist.values() if value is True)
    total = len(checklist)
    return {
        "patient": {
            "patientId": patient["id"],
            "displayName": patient["name"],
            "currentStage": patient["stage"],
            "currentStageLabel": stage_label(patient["stage"]),
            "responsible": patient.get("treatingDoctorName") or patient.get("doctor") or "Не назначен",
            "clientPathProfile": patient.get("nosology") or "Не указан",
            "routeStatus": "Завершён" if patient["stage"] == "completed" else "Активный",
            "checklistProgress": {"completed": completed, "total": total},
            "activeAttentionCount": len(attention.get("active") or []),
            "qualityIssueCount": len(issues),
            "untrusted": True,
        },
        "activeAttention": [
            {
                "reasonCode": issue["reasonCode"],
                "reasonLabel": issue["reasonLabel"],
                "eventDate": issue["eventDate"],
                "createdAt": issue["createdAt"],
                "untrusted": True,
            }
            for issue in attention.get("active", [])
        ],
        "qualityIssues": [
            {"code": issue["code"], "severity": issue["severity"], "title": issue["title"], "untrusted": True}
            for issue in issues[:10]
        ],
    }


def get_patient_timeline(conn: sqlite3.Connection, user: policy.CurrentUser, args: TimelineArgs) -> dict:
    patient = _require_patient(conn, user, args.patientId)
    rows = []
    for entry in patient["history"]:
        rows.append({
            "type": "stage",
            "stage": entry["stage"],
            "stageLabel": stage_label(entry["stage"]),
            "at": entry["enteredAt"],
            "untrusted": True,
        })
        for event in entry.get("events", []):
            rows.append({
                "type": "event",
                "plannedDate": event.get("date") or "",
                "actualDate": event.get("actualDate") or "",
                "treatmentType": event.get("treatmentType") or "",
                "completed": bool(event.get("actualDate") or event.get("noPlan")),
                "untrusted": True,
            })
    attention = patient_attention.list_for_patient(conn, user, args.patientId, limit=100)
    for issue in [*(attention.get("active") or []), *(attention.get("history") or [])]:
        rows.append({
            "type": "attention",
            "reasonCode": issue["reasonCode"],
            "reasonLabel": issue["reasonLabel"],
            "status": issue["status"],
            "at": issue["eventDate"] or issue["createdAt"],
            "untrusted": True,
        })
    rows.sort(key=lambda item: str(item.get("at") or item.get("plannedDate") or ""), reverse=True)
    return {"patientId": args.patientId, "items": rows[:args.limit]}


def list_attention_patients(conn: sqlite3.Connection, user: policy.CurrentUser, args: ListAttentionArgs) -> dict:
    cond, params = policy.patient_scope_filter(user)
    query_params: list[Any] = list(params)
    reason_clause = ""
    if args.reason:
        reason_clause = " AND i.reason_code = ?"
        query_params.append(args.reason)
    query_params.append(args.limit)
    rows = conn.execute(
        f"""SELECT patients.id, patients.name, patients.stage,
                   COUNT(i.id) AS active_count,
                   GROUP_CONCAT(DISTINCT i.reason_code) AS reason_codes,
                   MIN(i.created_at) AS opened_at
            FROM patient_attention_issues i
            JOIN patients ON patients.id = i.patient_id
            WHERE i.status = 'open' AND {cond}{reason_clause}
            GROUP BY patients.id
            ORDER BY active_count DESC, patients.name ASC, patients.id ASC
            LIMIT ?""",  # nosec B608 - scope condition is generated by policy; reason is allowlisted.
        query_params,
    ).fetchall()
    return {
        "patients": [
            {
                "patientId": row["id"],
                "displayName": row["name"],
                "currentStage": row["stage"],
                "currentStageLabel": stage_label(row["stage"]),
                "activeIssueCount": int(row["active_count"] or 0),
                "reasons": [
                    {"code": code, "label": patient_attention.reason_label(code)}
                    for code in sorted(set((row["reason_codes"] or "").split(",")) - {""})
                ],
                "openedAt": row["opened_at"],
                "untrusted": True,
            }
            for row in rows
        ]
    }


