def list_overdue_patients(conn: sqlite3.Connection, user: policy.CurrentUser, args: ListOverdueArgs) -> dict:
    quality = data_quality.evaluate(conn, user, today=today_local())
    rows = []
    for issue in quality["issues"]:
        if issue["code"] != "overdue_event":
            continue
        details = issue.get("details") or {}
        days = int(details.get("days_overdue") or 0)
        bucket, bucket_label = overdue_bucket(days)
        if args.bucket and args.bucket != bucket:
            continue
        rows.append({
            "patientId": issue["patient_id"],
            "displayName": issue["patient_name"],
            "daysOverdue": days,
            "bucket": bucket,
            "bucketLabel": bucket_label,
            "shortEventLabel": "Плановое событие",
            "untrusted": True,
        })
    rows.sort(key=lambda item: (-item["daysOverdue"], item["displayName"], item["patientId"]))
    return {"patients": rows[:args.limit]}


def get_today_work(conn: sqlite3.Connection, user: policy.CurrentUser, args: EmptyArgs) -> dict:
    today = today_local().isoformat()
    cond, params = policy.patient_scope_filter(user)
    event_rows = conn.execute(
        f"""SELECT patients.id, patients.name, patients.stage, e.date, e.time
            FROM events e
            JOIN history_entries h ON h.id = e.history_entry_id
            JOIN patients ON patients.id = h.patient_id
            WHERE {cond}
              AND patients.stage != 'completed'
              AND e.date = ?
              AND (e.actual_date IS NULL OR e.actual_date = '')
              AND COALESCE(e.no_plan, 0) = 0
            ORDER BY e.time ASC, patients.name ASC, e.id ASC
            LIMIT 30""",  # nosec B608 - scope condition is generated by policy.
        [*params, today],
    ).fetchall()
    attention = list_attention_patients(conn, user, ListAttentionArgs(limit=10))
    overdue = list_overdue_patients(conn, user, ListOverdueArgs(limit=10))
    return {
        "date": today,
        "eventsToday": [
            {
                "patientId": row["id"],
                "displayName": row["name"],
                "currentStage": row["stage"],
                "time": row["time"] or "",
                "untrusted": True,
            }
            for row in event_rows
        ],
        "attentionPatients": attention["patients"],
        "overduePatients": overdue["patients"],
    }


