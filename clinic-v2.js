            formatEventText(ev, isPending, treatmentTypeNames) {
                const typeText = ev.treatmentType ? `, тип: ${treatmentTypeNames[ev.treatmentType] || ev.treatmentType}` : '';
                if (ev.noPlan) {
                    const actualText = ev.actualDate ? `${ev.actualDate}${ev.actualTime ? ' ' + ev.actualTime : ''}` : 'дата не указана';
                    return { text: `${actualText}${typeText}`, status: 'состоялось (первичный контакт)' };
                }
                if (isPending) {
                    const dateText = ev.date ? `${ev.date}${ev.time ? ' ' + ev.time : ''}` : 'дата не указана';
                    return { text: `план: ${dateText}${typeText}`, status: 'ожидается' };
                }
                if (ev.actualDate) {
                    const actualText = `${ev.actualDate}${ev.actualTime ? ' ' + ev.actualTime : ''}`;
                    if (ev.matchedPlan) {
                        return { text: `${actualText}${typeText}`, status: 'состоялось по плану' };
                    }
                    const planText = ev.date ? `${ev.date}${ev.time ? ' ' + ev.time : ''}` : 'план не указан';
                    return { text: `факт: ${actualText} (план был: ${planText})${typeText}`, status: 'состоялось с отклонением от плана' };
                }
                const dateText = ev.date ? `${ev.date}${ev.time ? ' ' + ev.time : ''}` : 'дата не указана';
                return { text: `${dateText}${typeText}`, status: 'состоялось' };
            },

            getOccurrenceEffectiveDate(occ) {
                if (!occ.events || !occ.events.length) return null;
                const lastEvent = occ.events[occ.events.length - 1];
                const date = lastEvent.actualDate || lastEvent.date;
                const time = lastEvent.actualTime || lastEvent.time;
                if (!date) return null;
                return new Date(`${date}T${time || '00:00'}`);
            },

            addWorkingDays(startDate, days) {
                const d = new Date(startDate);
                d.setHours(0, 0, 0, 0);
                const total = Math.max(1, Math.round(days));
                let count = 0;
                while (count < total) {
                    d.setDate(d.getDate() + 1);
                    const dow = d.getDay();
                    if (dow !== 0 && dow !== 6) count++;
                }
                return d;
            },

            getStageDeadline(p, targetStageKey) {
                const nosology = this.nosologyData[p.nosology];
                if (!nosology) return null;
                const factor = this.getPriorityFactor(p.priority);

                if (targetStageKey === 'appointment') {
                    const primaryOcc = (p.history || []).find(o => o.stage === 'primary-appointment');
                    if (!primaryOcc) return null;
                    const baseDate = this.getOccurrenceEffectiveDate(primaryOcc);
                    if (!baseDate) return null;
                    return this.addWorkingDays(baseDate, nosology.stage1Days * factor);
                }

                if (targetStageKey === 'consult') {
                    const apptOcc = (p.history || []).find(o => o.stage === 'appointment');
                    if (!apptOcc) return null;
                    const baseDate = this.getOccurrenceEffectiveDate(apptOcc);
                    if (!baseDate) return null;
                    const stage2Base = (p.diseaseStage === 'IV') ? nosology.stage2StageIV : nosology.stage2Standard;
                    return this.addWorkingDays(baseDate, stage2Base * factor);
                }

                return null;
            },

