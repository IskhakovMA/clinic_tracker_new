        function getCookie(name) {
            const escaped = name.replace(/[.$?*|{}()[\]\\/+^]/g, '\\$&');
            const match = document.cookie.match(new RegExp('(?:^|; )' + escaped + '=([^;]*)'));
            return match ? decodeURIComponent(match[1]) : null;
        }

        async function apiFetch(path, options) {
            options = options || {};
            const opts = Object.assign({ credentials: 'include' }, options);
            opts.headers = Object.assign({}, options.headers);
            const method = (opts.method || 'GET').toUpperCase();
            if (opts.body !== undefined) {
                opts.headers['Content-Type'] = 'application/json';
            }
            if (method !== 'GET' && method !== 'HEAD') {
                const csrf = getCookie('clinic_csrf');
                if (csrf) opts.headers['X-CSRF-Token'] = csrf;
            }
            const response = await fetch(path, opts);
            if (!response.ok) {
                let detail = `Ошибка запроса (${response.status})`;
                try {
                    const data = await response.json();
                    if (data && typeof data.detail === 'string') detail = data.detail;
                    else if (data && data.detail) detail = JSON.stringify(data.detail);
                    else if (data && data.error) detail = data.error;
                } catch (e) { /* response body wasn't JSON */ }
                const err = new Error(detail);
                err.status = response.status;
                throw err;
            }
            if (response.status === 204) return null;
            const contentType = response.headers.get('content-type') || '';
            if (contentType.includes('application/json')) return response.json();
            return response;
        }

        function apiGetJson(path) { return apiFetch(path); }
        function apiPost(path, body) { return apiFetch(path, { method: 'POST', body: JSON.stringify(body === undefined ? {} : body) }); }
        function apiPatch(path, body) { return apiFetch(path, { method: 'PATCH', body: JSON.stringify(body === undefined ? {} : body) }); }
        function apiPut(path, body) { return apiFetch(path, { method: 'PUT', body: JSON.stringify(body === undefined ? {} : body) }); }
        function apiDelete(path) { return apiFetch(path, { method: 'DELETE' }); }

