            async init() {
                this.applyTheme(localStorage.getItem('theme') || 'light');
                try {
                    const me = await apiGetJson('/api/auth/me');
                    if (me && me.authenticated) {
                        await this.loadPatients();
                        this.showApp();
                        this.render();
                        this.maybeOfferLegacyMigration();
                    }
                } catch (e) {
                    // Backend unreachable or session invalid — stay on the login screen.
                }
            },

            maybeOfferLegacyMigration() {
                if (this.patients.length > 0) return;
                let legacy;
                try {
                    legacy = JSON.parse(localStorage.getItem('patients') || 'null');
                } catch (e) {
                    return;
                }
                if (!Array.isArray(legacy) || legacy.length === 0) return;
                this.showMigrationBanner(legacy.length);
            },

            showMigrationBanner(count) {
                const bar = document.createElement('div');
                bar.id = 'legacyMigrationBanner';
                bar.style.cssText = 'position:fixed;top:0;left:0;right:0;z-index:9999;background:var(--warning-soft, #fff3cd);color:var(--text-primary);border-bottom:1px solid var(--warning, #f0ad4e);padding:10px 16px;display:flex;gap:12px;align-items:center;justify-content:center;font-size:13px;';
                bar.innerHTML = `
                    <span>В этом браузере найдены данные пациентов из старой версии (${count} шт.). Перенести их на сервер?</span>
                    <button type="button" class="filter-btn" id="legacyMigrationConfirm">Перенести</button>
                    <button type="button" class="filter-btn" id="legacyMigrationDismiss">Не сейчас</button>
                `;
                document.body.prepend(bar);
                document.getElementById('legacyMigrationDismiss').addEventListener('click', () => bar.remove());
                document.getElementById('legacyMigrationConfirm').addEventListener('click', () => this.runLegacyMigration(bar));
            },

            async runLegacyMigration(bannerEl) {
                const raw = localStorage.getItem('patients');
                if (!raw) { bannerEl.remove(); return; }
                try {
                    const preview = await apiPost('/api/migrate/localstorage/preview', { raw });
                    if (!preview.valid) {
                        alert('Не удалось перенести данные: файл не прошёл проверку.\n\n' + JSON.stringify(preview.errors).slice(0, 500));
                        return;
                    }
                    const proceed = confirm(`Будет перенесено ${preview.totalRecords} пациент(ов) на сервер. Продолжить?`);
                    if (!proceed) return;
                    await apiPost('/api/migrate/localstorage/commit', { raw, mode: 'add' });
                    const removeLocal = confirm('Перенос завершён. Удалить локальную копию данных из этого браузера?');
                    if (removeLocal) {
                        localStorage.removeItem('patients');
                        localStorage.removeItem('user');
                    }
                    await this.loadPatients();
                    bannerEl.remove();
                    this.render();
                } catch (e) {
                    alert('Перенос не выполнен: ' + e.message);
                }
            },

            applyTheme(theme) {
                document.documentElement.setAttribute('data-theme', theme);
                const btn = document.getElementById('themeToggle');
                if (btn) btn.textContent = theme === 'dark' ? 'Светлая тема' : 'Тёмная тема';
            },

            toggleTheme() {
                const current = document.documentElement.getAttribute('data-theme') || 'light';
                const next = current === 'dark' ? 'light' : 'dark';
                localStorage.setItem('theme', next);
                this.applyTheme(next);
            },


