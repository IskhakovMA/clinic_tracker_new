            getDaysUntil(dateStr) {
                if (!dateStr) return null;
                const today = new Date();
                today.setHours(0, 0, 0, 0);
                const eventDate = new Date(dateStr);
                eventDate.setHours(0, 0, 0, 0);
                const days = Math.floor((eventDate - today) / (1000*60*60*24));
                return days;
            },

